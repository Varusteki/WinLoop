        /// <summary>解析 "x,y x,y ..." 形式的折线；点数不足 3 返回 null。</summary>
        public static Point[] ParseOne(string text)
        {
            if (string.IsNullOrWhiteSpace(text)) return null;
            var list = new List<Point>();
            foreach (string pair in text.Split(' '))
            {
                int comma = pair.IndexOf(',');
                if (comma <= 0) continue;
                double x, y;
                if (double.TryParse(pair.Substring(0, comma), System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out x) &&
                    double.TryParse(pair.Substring(comma + 1), System.Globalization.NumberStyles.Float,
                        System.Globalization.CultureInfo.InvariantCulture, out y))
                {
                    list.Add(new Point(x, y));
                }
            }
            return list.Count >= 3 ? list.ToArray() : null;
        }

        public static List<Point[]> Parse(string[] source)
        {
            var result = new List<Point[]>();
            if (source == null) return result;
            foreach (string item in source)
            {
                Point[] loop = ParseOne(item);
                if (loop != null) result.Add(loop);
            }
            return result;
        }
    }
